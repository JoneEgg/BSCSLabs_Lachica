<?php
// FUNCTIONS ======
            
function addition(float $num1, float $num2){
    return (float) $num1+$num2;
}

function subtraction(float $num1, float $num2){
    return (float) $num1-$num2;
}

function multiply(float $num1, float $num2){
    return (float) $num1*$num2;
}
function divide(float $num1, float $num2){
    return (float) $num1/$num2;
}

?>